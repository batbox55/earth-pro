    static func fixture() -> (Data,Data) {
        var body = Data()
        func int(_ value: Int, to data: inout Data, big: Bool = false) {
            let v = UInt32(value); for i in 0..<4 { data.append(UInt8(truncatingIfNeeded: v >> (8*(big ? 3-i : i)))) }
        }
        func number(_ value: Double, to data: inout Data) { for i in 0..<8 { data.append(UInt8(truncatingIfNeeded:value.bitPattern >> (8*i))) } }
        // Deliberately hole-first to exercise containment independent of ring order.
        let rings = [
            [[-117.99,33.01],[-117.98,33.01],[-117.98,33.02],[-117.99,33.02],[-117.99,33.01]],
            [[-118.0,33.0],[-118.0,33.03],[-117.97,33.03],[-117.97,33.0],[-118.0,33.0]],
            [[-117.96,33.0],[-117.96,33.01],[-117.95,33.01],[-117.95,33.0],[-117.96,33.0]]
        ]
        int(5,to:&body); for v in [-118.0,33.0,-117.95,33.03] { number(v,to:&body) }
        int(rings.count,to:&body); int(15,to:&body)
        for start in [0,5,10] { int(start,to:&body) }
        for ring in rings { for p in ring { number(p[0],to:&body); number(p[1],to:&body) } }
        var shp = Data(); int(9994,to:&shp,big:true); shp.append(Data(repeating:0,count:20)); int((108+body.count)/2,to:&shp,big:true); int(1000,to:&shp); int(5,to:&shp)
        for v in [-118.0,33.0,-117.95,33.03,0,0,0,0] { number(v,to:&shp) }
        int(1,to:&shp,big:true); int(body.count/2,to:&shp,big:true); shp.append(body)
        var dbf = Data(repeating:0,count:65); dbf[0]=3; dbf[4]=1; dbf[8]=65; dbf[10]=17
        dbf.replaceSubrange(32..<36,with:Data("ZONE".utf8)); dbf[43]=67; dbf[48]=16; dbf[64]=13
        dbf.append(32); dbf.append(Data("Residential     ".utf8)); dbf.append(0x1a)
        return (shp,dbf)
    }
    func testShapefilePreservesDBFMultipartAndHolesAndRejectsTruncation() throws {
        let (shp,dbf) = Self.fixture()
        let result = try ShapefileService.decode(shp:shp,dbf:dbf,projection:ShapefileProjection(Self.wgs))
        XCTAssertEqual(result.features.count,2)
        XCTAssertEqual(result.features[0].kind,.polygon)
        XCTAssertEqual(result.features[0].holes?.count,1)
        XCTAssertEqual(result.features[0].attributes?["ZONE"],"Residential")
        XCTAssertEqual(result.legend.first?.label,"Residential")
        XCTAssertTrue(result.features.allSatisfy(\.isValid))
        XCTAssertThrowsError(try ShapefileService.decode(shp:shp.dropLast(),dbf:dbf,projection:ShapefileProjection(Self.wgs)))
        XCTAssertThrowsError(try ShapefileService.decode(shp:shp,dbf:Data(dbf.prefix(64)),projection:ShapefileProjection(Self.wgs)))
        let roundtrip = try JSONDecoder().decode([EarthFeature].self,from:JSONEncoder().encode(result.features))
        XCTAssertEqual(roundtrip,result.features)
    }
    func testBundleAndZipImportWithSourceRendererAndMissingPRJ() throws {
        let folder = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at:folder,withIntermediateDirectories:true)
        defer { try? FileManager.default.removeItem(at:folder) }
        let (shp,dbf) = Self.fixture()
        try shp.write(to:folder.appendingPathComponent("zoning.shp")); try dbf.write(to:folder.appendingPathComponent("zoning.dbf"))
        XCTAssertThrowsError(try ShapefileService.read(folder))
        try Data(Self.wgs.utf8).write(to:folder.appendingPathComponent("zoning.prj"))
        let renderer = #"{"type":"uniqueValue","field1":"ZONE","uniqueValueInfos":[{"value":"Residential","label":"Homes","symbol":{"type":"esriSFS","style":"esriSFSSolid","color":[200,80,30,128],"outline":{"color":[20,30,40,255],"width":1}}}]}"#
        try Data(renderer.utf8).write(to:folder.appendingPathComponent("zoning.json"))
        let result = try ShapefileService.read(folder)
        XCTAssertEqual(result.features.first?.vectorStyle?.fill,"#C8501E")
        XCTAssertEqual(result.legend.first?.label,"Homes")
        let archive = folder.appendingPathComponent("zoning.zip")
        let zip = Process(); zip.executableURL = URL(fileURLWithPath:"/usr/bin/zip"); zip.currentDirectoryURL = folder
        zip.arguments = ["-q",archive.path,"zoning.shp","zoning.dbf","zoning.prj","zoning.json"]
        try zip.run(); zip.waitUntilExit(); XCTAssertEqual(zip.terminationStatus,0)
        let zipped = try ShapefileService.read(archive)
        XCTAssertEqual(zipped.features.map(\.points),result.features.map(\.points))
        XCTAssertEqual(zipped.features.first?.holes,result.features.first?.holes)
        XCTAssertEqual(zipped.legend,result.legend)
    }
    func testArcGISClassificationsAndGeoJSONSimpleStyle() throws {
        let json = #"{"type":"FeatureCollection","features":[{"type":"Feature","properties":{"ZONE":"R","score":12},"geometry":{"type":"Polygon","coordinates":[[[0,0],[1,0],[1,1],[0,0]]]}}]}"#
        var result = try CustomDataService.decodeGeoJSON(data:Data(json.utf8))
        let metadata = #"{"drawingInfo":{"renderer":{"type":"classBreaks","field":"score","minValue":0,"classBreakInfos":[{"classMaxValue":10,"label":"Low","symbol":{"type":"esriSFS","color":[0,255,0,100]}},{"classMaxValue":20,"label":"High","symbol":{"type":"esriSFS","color":[255,0,0,100]}}]}}}"#
        try XCTUnwrap(VectorStyling.arcGIS(Data(metadata.utf8))).apply(&result)
        XCTAssertEqual(result.features[0].vectorStyle?.fill,"#FF0000")
        XCTAssertEqual(result.legend.map(\.label),["Low","High"])
        XCTAssertEqual(result.stylingNotice,"Publisher styling")
        let simple = json.replacingOccurrences(of:"\"ZONE\":\"R\"",with:"\"fill\":\"#123456\",\"fill-opacity\":0.6")
        let styled = try CustomDataService.decodeGeoJSON(data:Data(simple.utf8))
        XCTAssertEqual(styled.features[0].vectorStyle?.fill,"#123456")
        XCTAssertEqual(styled.features[0].vectorStyle?.fillOpacity,0.6)
    }
