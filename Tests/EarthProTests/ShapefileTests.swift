    func testTransparentPublisherStyleGetsVisibleCategorizedFallback() throws {
        let record = #"{"type":"Feature","properties":{"ZONE":"R"},"geometry":{"type":"Polygon","coordinates":[[[0,0],[1,0],[1,1],[0,0]]]}}"#
        var result = try CustomDataService.decodeGeoJSON(data:Data(record.utf8))
        VectorStyling.parse(["type":"simple","symbol":["type":"esriSFS","color":[0,0,0,0],"outline":["color":[143,102,82,0],"width":0.5]]]).apply(&result)
        XCTAssertTrue(result.features[0].vectorStyle?.hasVisibleGeometry == true)
        XCTAssertEqual(result.legend.first?.label,"R")
        XCTAssertEqual(result.features[0].vectorStyle,result.legend.first?.style)
        XCTAssertTrue(result.stylingNotice?.contains("fully transparent") == true)
        VectorStyling.parse(["type":"unsupported"]).apply(&result)
        XCTAssertEqual(result.legend.first?.label,"R")
        XCTAssertTrue(result.stylingNotice?.contains("unsupported") == true)
        XCTAssertEqual(VectorStyling.symbol(["type":"esriSLS","color":[0,92,230,255],"width":1])?.symbolKind,.path)
    }
    func testFloodNullClassificationAndSimplifiedHatchLegend() throws {
        let data = Data(#"{"type":"Feature","properties":{"FLD_ZONE":"A","ZONE_SUBTY":null},"geometry":{"type":"Polygon","coordinates":[[[0,0],[1,0],[1,1],[0,0]]]}}"#.utf8)
        var result = try CustomDataService.decodeGeoJSON(data:data,requiredFields:["FLD_ZONE","ZONE_SUBTY"])
        let symbol: [String:Any] = ["type":"esriSFS","style":"esriSFSDiagonalCross","color":[0,230,255,255],"outline":["color":[0,0,0,255],"width":1]]
        let renderer = VectorStyling.parse(["type":"uniqueValue","field1":"FLD_ZONE","field2":"ZONE_SUBTY","fieldDelimiter":";","uniqueValueInfos":[["value":"A;<Null>","label":"1% Annual Chance Flood Hazard","symbol":symbol]]])
