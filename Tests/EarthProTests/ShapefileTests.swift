    }
    func testGlobeFillProducesHoleMaskAndBoundedMesh() throws {
        let (shp,dbf) = Self.fixture()
        let feature = try XCTUnwrap(ShapefileService.decode(shp:shp,dbf:dbf,projection:ShapefileProjection(Self.wgs)).features.first)
        let node = try XCTUnwrap(GlobePolygonFill.node(feature,terrain:false,size:128))
        XCTAssertLessThanOrEqual(node.geometry?.sources.first?.vectorCount ?? Int.max, 4225)
        let image = try XCTUnwrap(node.geometry?.firstMaterial?.diffuse.contents) as! CGImage
        let pixels = try XCTUnwrap(image.dataProvider?.data) as Data
        // Center is the hole; a corner lies in the filled exterior.
        XCTAssertEqual(pixels[64*image.bytesPerRow+64*4+3],0)
        XCTAssertGreaterThan(pixels[10*image.bytesPerRow+10*4+3],0)
    }
