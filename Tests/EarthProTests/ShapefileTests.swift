    func testRetriesOnlyTransientNetworkFailuresWithoutChangingTrust() {
        XCTAssertTrue(CustomDataService.shouldRetry(URLError(.secureConnectionFailed)))
        XCTAssertFalse(CustomDataService.shouldRetry(URLError(.serverCertificateUntrusted)))
        XCTAssertFalse(CustomDataService.shouldRetry(URLError(.serverCertificateHasBadDate)))
        XCTAssertFalse(CustomDataService.shouldRetry(URLError(.cancelled)))
    }
    func testSourceFieldsBeyondAttributePreviewArePreserved() throws {
        var properties: [String:Any] = Dictionary(uniqueKeysWithValues:(0..<70).map { ("a\($0)","value") })
