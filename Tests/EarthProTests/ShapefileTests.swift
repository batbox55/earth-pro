        let mercator = try projection("Mercator_Auxiliary_Sphere", #"PARAMETER["Central_Meridian",0],PARAMETER["False_Easting",0],PARAMETER["False_Northing",0]"#)
        let m = try mercator.point(x: -13135699.913, y: 4005997.9575318177)
        XCTAssertEqual(m[0],-118,accuracy:0.000001); XCTAssertEqual(m[1],33.83,accuracy:0.00001)
        let utm = try projection("Transverse_Mercator", #"PARAMETER["Central_Meridian",-117],PARAMETER["Latitude_Of_Origin",0],PARAMETER["False_Easting",500000],PARAMETER["False_Northing",0],PARAMETER["Scale_Factor",0.9996]"#)
        let u = try utm.point(x:500000,y:3762155.9776)
        XCTAssertEqual(u[0],-117,accuracy:0.000001); XCTAssertEqual(u[1],34,accuracy:0.000001)
